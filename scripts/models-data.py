#!/usr/bin/env python3
"""Build the Models tab data from the Codex of Azeroth database.

    python3 scripts/models-data.py [--database path/to/codex.sqlite]

Reads the codex's `models` table (every creature display the client ships)
and writes catalog/models.json and MediaLab_Models/data.lua. Build the codex
first (`python3 -m codex` in that project). Derived facts only; no artwork.
"""

import argparse
import json
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
JSON_OUT = ROOT / "catalog" / "models.json"
ADDON_OUT = ROOT / "MediaLab_Models" / "data.lua"
SCHEMA = 1  # the codex schema version this was written for


def lua_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def load(db):
    meta = dict(db.execute("SELECT key, value FROM meta"))
    if int(meta["schema_version"]) != SCHEMA:
        sys.exit(f"codex schema {meta['schema_version']}, expected {SCHEMA}; update this script")
    rows = db.execute("SELECT id, name, type, family, skins, model_file FROM models ORDER BY id").fetchall()
    items = [{"id": r[0], "name": r[1], "type": r[2], "family": r[3], "skins": json.loads(r[4]), "model": r[5]}
             for r in rows]
    return meta, items


def write_json(meta, items, path=JSON_OUT):
    header = json.dumps({
        "kind": "models",
        "source": {"client": meta["client_build"], "database": "codex-of-azeroth",
                   "schema_version": int(meta["schema_version"]), "names": "wowdev/wow-listfile",
                   "columns": "wowdev/WoWDBDefs"},
        "count": len(items),
    })[:-1]
    body = ",\n".join(json.dumps(item, separators=(",", ":")) for item in items)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f'{header}, "items": [\n{body}\n]}}\n')


def write_addon(items, path=ADDON_OUT):
    # One tab-separated string per display ID, split by MediaLab only when
    # indexing. Fields: name, type, family, model file ID, skins.
    lines = ["-- Generated by scripts/models-data.py from the Codex of Azeroth. Derived facts only; no artwork.",
             "MediaLabModels = {"]
    for item in items:
        fields = [item["name"], item["type"], item["family"], str(item["model"]), ",".join(item["skins"])]
        lines.append(f"[{item['id']}]={lua_string(chr(9).join(fields))},")
    lines.append("}")
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines) + "\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--database", type=Path, help="codex.sqlite (default: the sibling codex project's)")
    args = parser.parse_args()
    if args.database:
        path = args.database
    else:
        sys.path.insert(0, str(ROOT / "scripts"))
        import codex_source
        path = codex_source.database()
    db = sqlite3.connect(path)
    meta, items = load(db)
    db.close()
    write_json(meta, items)
    write_addon(items)
    size = ADDON_OUT.stat().st_size
    print(f"models: {len(items):,} creature displays from client {meta['client_build']} -> "
          f"{JSON_OUT.relative_to(ROOT)}, {ADDON_OUT.relative_to(ROOT)} ({size / 1e6:.1f} MB)")


if __name__ == "__main__":
    main()
