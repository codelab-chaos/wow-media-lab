#!/usr/bin/env python3
"""Refresh MediaLab's data from the Codex of Azeroth.

    python3 scripts/sync-codex.py [--database path/to/codex.sqlite]

MediaLab is a stand-alone addon: everything it lists ships in its own
generated data files, committed with it. This script regenerates those files
from the codex database (CODEX_DIR, or ../codex-of-azeroth next to this repo),
the project that reads the game. Facts only: names, paths and IDs.

Each output below is one row: the file it writes, the codex tables and
columns it reads, and the function that renders it.
"""

import argparse
import json
import os
import sqlite3
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HEADER = "-- Generated by scripts/sync-codex.py from the Codex of Azeroth."


def lua_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def lua_list(name, rows):
    lines = [f"ML.{name} = {{"]
    for row in rows:
        if isinstance(row, (list, tuple)):
            lines.append("    {" + ", ".join(json.dumps(value) for value in row) + "},")
        else:
            lines.append(f"    {json.dumps(row)},")
    lines.append("}")
    return lines


def namespaced(note, body):
    return "\n".join([f"{HEADER} {note}", "local _, ML = ...", *body, ""])


def art(db, meta):
    paths = sorted((row[0] for row in db.execute("SELECT path FROM textures")), key=str.lower)
    atlases = sorted(row[0] for row in db.execute("SELECT name FROM atlases"))
    # Addons cannot read a texture file's size; the codex reads it from the file.
    sizes = sorted(db.execute("SELECT path, width, height FROM textures WHERE width IS NOT NULL AND is_icon = 0"),
                   key=lambda row: row[0].lower())
    return namespaced("References only; no artwork included.", [
        f"ML.SourceVersion = {json.dumps(meta['ui_source_version'])}",
        f"ML.SourceCommit = {json.dumps(meta['ui_source_commit'])}",
        *lua_list("TexturePaths", paths),
        *lua_list("AtlasFallback", atlases),
        "ML.TextureSizes = {",
        *[f"    [{json.dumps(path)}] = {{{width}, {height}}}," for path, width, height in sizes],
        "}",
    ])


def sounds(db, _meta):
    return namespaced("SOUNDKIT names and IDs; no audio included.",
                      lua_list("SoundKits", sorted(db.execute("SELECT name, id FROM sound_kits"))))


FONT_TAGS = ("Font", "FontFamily")


def templates(db, _meta):
    rows = sorted(db.execute("SELECT name, type, inherits, source FROM templates"))
    return namespaced("Virtual XML templates: name, tag, inherits, source file.", [
        *lua_list("Templates", [row for row in rows if row[1] not in FONT_TAGS]),
        *lua_list("FontTemplates", [row for row in rows if row[1] in FONT_TAGS]),
    ])


def keyed(global_name, rows):
    # One tab-separated string per ID keeps memory low; MediaLab splits it only when indexing.
    lines = [f"{HEADER} Derived facts only; no artwork.", f"{global_name} = {{"]
    lines += [f"[{key}]={lua_string(chr(9).join(fields))}," for key, fields in rows]
    lines.append("}")
    return "\n".join(lines) + "\n"


def icons(db, _meta):
    # Fields: name, colors, subject, tags, description.
    rows = db.execute("SELECT id, name, colors, subject, tags, description FROM icons ORDER BY id")
    return keyed("MediaLabIconMeta", ((fdid, [name, ",".join(json.loads(colors)), subject or "",
                                              ",".join(json.loads(tags)), description or ""])
                                      for fdid, name, colors, subject, tags, description in rows))


def models(db, _meta):
    # Fields: name, type, family, model file ID, skins.
    rows = db.execute("SELECT id, name, type, family, model_file, skins FROM models ORDER BY id")
    return keyed("MediaLabModels", ((display, [name, kind, family, str(model), ",".join(json.loads(skins))])
                                    for display, name, kind, family, model, skins in rows))


USAGE_LIMIT = 160  # characters of "what plays it" per sound


def usage_text(db):
    """{sound: "Creature murloc: Aggro, Death; Music Elwynn Forest: Day"}."""
    groups = {}
    for sound, kind, name, role in db.execute("SELECT sound, kind, name, role FROM sound_usage ORDER BY sound, kind, name, role"):
        key = (kind.capitalize() + " " + (name or "")).strip()
        roles = groups.setdefault(sound, {}).setdefault(key, [])
        if role not in roles:
            roles.append(role)
    text = {}
    for sound, users in groups.items():
        line = "; ".join(f"{who}: {', '.join(roles)}" for who, roles in users.items())
        text[sound] = line if len(line) <= USAGE_LIMIT else line[:USAGE_LIMIT - 3].rsplit(";", 1)[0] + "; ..."
    return text


def sounds_data(db, _meta):
    # Fields: name, category, folder, SOUNDKIT constant, file count, length in ms,
    # waveform, volume (0-100), what plays it.
    usage = usage_text(db)
    rows = db.execute("SELECT id, name, category, folder, constant, files, duration_ms, waveform, volume "
                      "FROM sounds ORDER BY id")
    return keyed("MediaLabSounds", (
        (kit, [name, category, folder or "", constant or "", str(files), str(ms or ""), wave or "",
               str(round(volume * 100)) if volume is not None else "", usage.get(kit, "")])
        for kit, name, category, folder, constant, files, ms, wave, volume in rows))


OUTPUTS = [
    {"path": "MediaLab/data/art.lua", "render": art,
     "reads": {"textures": {"path", "is_icon", "width", "height"}, "atlases": {"name"}}},
    {"path": "MediaLab/data/sounds.lua", "render": sounds, "reads": {"sound_kits": {"name", "id"}}},
    {"path": "MediaLab/data/templates.lua", "render": templates,
     "reads": {"templates": {"name", "type", "inherits", "source"}}},
    {"path": "MediaLab_Icons/data.lua", "render": icons,
     "reads": {"icons": {"id", "name", "colors", "subject", "tags", "description"}}},
    {"path": "MediaLab_Sounds/data.lua", "render": sounds_data,
     "reads": {"sounds": {"id", "name", "category", "folder", "constant", "files", "duration_ms", "waveform", "volume"},
               "sound_usage": {"sound", "kind", "name", "role"}}},
    {"path": "MediaLab_Models/data.lua", "render": models,
     "reads": {"models": {"id", "name", "type", "family", "model_file", "skins"}}},
]


def check(db):
    """The codex's schema version rises whenever any table changes, so check the
    columns MediaLab reads rather than the version."""
    problems = []
    for output in OUTPUTS:
        for table, wanted in output["reads"].items():
            missing = wanted - {row[1] for row in db.execute(f"PRAGMA table_info({table})")}
            if missing:
                problems.append(f"{table}: no {', '.join(sorted(missing))}")
    if problems:
        sys.exit("The codex database lacks what MediaLab reads; update this script.\n  " + "\n  ".join(problems))


def database():
    folder = Path(os.environ.get("CODEX_DIR") or ROOT.parent / "codex-of-azeroth")
    path = folder / "data" / "codex.sqlite"
    if not path.is_file():
        sys.exit(f"No codex database at {path}. Build it in the Codex of Azeroth (python3 -m codex), "
                 "or pass --database.")
    return path


def sync(path, root=ROOT):
    db = sqlite3.connect(path)
    try:
        check(db)
        meta = dict(db.execute("SELECT key, value FROM meta"))
        written = []
        for output in OUTPUTS:
            target = root / output["path"]
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(output["render"](db, meta))
            written.append((output["path"], target.stat().st_size))
        return meta, written
    finally:
        db.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--database", type=Path, help="codex.sqlite (default: the sibling codex project's)")
    args = parser.parse_args()
    meta, written = sync(args.database or database())
    print(f"codex: client {meta.get('client_build')}, UI source {meta.get('ui_source_version')}, "
          f"schema {meta.get('schema_version')}")
    for path, size in written:
        print(f"  {path} ({size / 1e3:,.0f} kB)")


if __name__ == "__main__":
    main()
