#!/usr/bin/env python3
"""Generate MediaLab's reference catalog from the Blizzard UI source.

Writes references only (names, paths, IDs); no Blizzard artwork or audio is
copied. Runtime enumeration in the client is preferred wherever it exists;
these lists are the fallback and the source of extra metadata.
"""

import argparse
import io
import json
from pathlib import Path
import re
import subprocess
import tarfile

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "MediaLab" / "data"

LUA_STRING = re.compile(r'''(["'])((?:\\.|(?!\1)[^\\\r\n])*?)\1''')
LONG_STRING = re.compile(r"\[\[([^\]\r\n]+)\]\]")
XML_ATLAS = re.compile(r'''\batlas\s*=\s*["']([^"']+)["']''', re.I)
LUA_ATLAS = re.compile(
    r'''(?:SetAtlas\s*\(\s*|\b(?:atlas|atlasName|iconAtlas|backgroundAtlas)\s*=\s*)["']([\w-]+)["']''',
    re.I,
)
SOUNDKIT_ROW = re.compile(r"^\s*([A-Z][A-Z0-9_]*)\s*=\s*(\d+)\s*,", re.M)
XML_TAG = re.compile(r"<([A-Za-z]+)\b([^<>]*?)/?>", re.S)
XML_ATTR = re.compile(r'''([A-Za-z]+)\s*=\s*["']([^"']*)["']''')
FONT_TAGS = {"Font", "FontFamily"}
SOUNDKIT_FILE = "Interface/AddOns/Blizzard_SharedXML/Mainline/SoundKitConstants.lua"


def texture_path(value):
    value = value.replace("\\\\", "\\").replace("/", "\\")
    # Reject format strings, concatenation fragments and other non-literal paths.
    if not re.fullmatch(r"Interface\\[\w\\ .&'!-]+(?:\.(?:blp|tga))?", value, re.I):
        return None
    if "\\AddOns\\" in value or value.endswith("\\"):
        return None
    if value.lower().endswith((".lua", ".xml", ".ttf", ".mp3", ".ogg", ".wav", ".m2")):
        return None
    return re.sub(r"\.(?:blp|tga)$", "", value, flags=re.I)


def extract_art(text, is_xml=False):
    strings = [match[1] for match in LUA_STRING.findall(text)]
    strings.extend(LONG_STRING.findall(text))
    paths = {path for value in strings if (path := texture_path(value))}
    atlases = set(XML_ATLAS.findall(text) if is_xml else LUA_ATLAS.findall(text))
    return paths, {name for name in atlases if re.fullmatch(r"[\w-]+", name)}


def extract_sounds(text):
    """SOUNDKIT constant rows, as (name, id) pairs in source order."""
    return [(name, int(value)) for name, value in SOUNDKIT_ROW.findall(text)]


def extract_templates(text):
    """Virtual XML templates as (name, tag, inherits) triples."""
    found = []
    for tag, body in XML_TAG.findall(text):
        attrs = dict(XML_ATTR.findall(body))
        name = attrs.get("name", "")
        if attrs.get("virtual", "").lower() != "true" or not re.fullmatch(r"[A-Za-z_]\w*", name):
            continue
        found.append((name, tag, attrs.get("inherits", "")))
    return found


def source_rank(path):
    """Prefer shared and mainline definitions over game-family overrides."""
    return (1 if re.search(r"/(Classic|Vanilla|TBC|Wrath|Cata|Mists)/", path) else 0, path)


def lua_list(name, rows):
    lines = [f"ML.{name} = {{"]
    for row in rows:
        if isinstance(row, (list, tuple)):
            lines.append("    {" + ", ".join(json.dumps(value) for value in row) + "},")
        else:
            lines.append(f"    {json.dumps(row)},")
    lines.append("}")
    return lines


def write(path, header, body):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join([
        f"-- Generated by scripts/build-catalog.py. {header}",
        "local _, ML = ...",
        *body,
        "",
    ]))


def build(source, ref, output):
    def git(*args):
        return subprocess.check_output(["git", "-C", str(source), *args])

    commit = git("rev-parse", ref).decode().strip()
    version = git("show", f"{ref}:version.txt").decode().strip()
    archive = git("archive", ref, "Interface")
    paths, atlases, sounds, templates = {}, set(), [], {}
    with tarfile.open(fileobj=io.BytesIO(archive)) as files:
        for member in files:
            if not member.isfile() or not member.name.endswith((".lua", ".xml")):
                continue
            text = files.extractfile(member).read().decode("utf-8", errors="replace")
            is_xml = member.name.endswith(".xml")
            found_paths, found_atlases = extract_art(text, is_xml)
            for path in sorted(found_paths):
                paths.setdefault(path.lower(), path)
            atlases.update(found_atlases)
            if member.name == SOUNDKIT_FILE:
                sounds = extract_sounds(text)
            if is_xml:
                where = member.name.removeprefix("Interface/AddOns/").removeprefix("Interface/")
                for name, tag, inherits in extract_templates(text):
                    current = templates.get(name)
                    if not current or source_rank(where) < source_rank(current[3]):
                        templates[name] = (name, tag, inherits, where)

    seen, kits = set(), []
    for name, kit in sounds:
        if name not in seen:
            seen.add(name)
            kits.append((name, kit))
    controls = [row for row in templates.values() if row[1] not in FONT_TAGS]
    fonts = [row for row in templates.values() if row[1] in FONT_TAGS]
    meta = [
        f"ML.SourceVersion = {json.dumps(version)}",
        f"ML.SourceCommit = {json.dumps(commit)}",
    ]
    write(output / "art.lua", "References only; no artwork included.", [
        *meta,
        *lua_list("TexturePaths", [path for _, path in sorted(paths.items())]),
        *lua_list("AtlasFallback", sorted(atlases)),
    ])
    write(output / "sounds.lua", "SOUNDKIT names and IDs; no audio included.",
          lua_list("SoundKits", sorted(kits)))
    write(output / "templates.lua", "Virtual XML templates: name, tag, inherits, source file.", [
        *lua_list("Templates", sorted(controls)),
        *lua_list("FontTemplates", sorted(fonts)),
    ])
    print(f"{len(paths):,} textures, {len(atlases):,} atlases, {len(kits):,} sound kits, "
          f"{len(controls):,} templates, {len(fonts):,} fonts ({version}, {commit[:12]})")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=Path("/home/chadneff/git/hub/wow-ui-source"))
    parser.add_argument("--ref", default="origin/forever")
    parser.add_argument("--output", type=Path, default=DATA)
    args = parser.parse_args()
    build(args.source, args.ref, args.output)
