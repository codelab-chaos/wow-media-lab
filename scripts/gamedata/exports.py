"""Files generated from the published database: one function per output,
each reading only catalog/wow-data.sqlite."""

import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MODELS_JSON = ROOT / "catalog" / "models.json"
MODELS_ADDON = ROOT / "MediaLab_Models" / "data.lua"


def lua_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def shown(path):
    return str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else path.name


def meta(db):
    return dict(db.execute("SELECT key, value FROM meta"))


def models(db):
    rows = db.execute("SELECT id, name, type, family, skins, model_file FROM models ORDER BY id").fetchall()
    return [{"id": r[0], "name": r[1], "type": r[2], "family": r[3], "skins": json.loads(r[4]), "model": r[5]}
            for r in rows]


def models_json(db, path=MODELS_JSON):
    items, info = models(db), meta(db)
    header = json.dumps({
        "kind": "models",
        "source": {"client": info["client_build"], "database": "wow-data.sqlite",
                   "schema_version": int(info["schema_version"]), "names": "wowdev/wow-listfile",
                   "columns": "wowdev/WoWDBDefs"},
        "count": len(items),
    })[:-1]
    body = ",\n".join(json.dumps(item, separators=(",", ":")) for item in items)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f'{header}, "items": [\n{body}\n]}}\n')
    return f"{shown(path)} ({len(items):,} models)"


def models_addon(db, path=MODELS_ADDON):
    # One tab-separated string per display ID, split by MediaLab only when
    # indexing. Fields: name, type, family, model file ID, skins.
    lines = ["-- Generated by scripts/game-data.py from wow-data.sqlite. Derived facts only; no artwork.",
             "MediaLabModels = {"]
    for item in models(db):
        fields = [item["name"], item["type"], item["family"], str(item["model"]), ",".join(item["skins"])]
        lines.append(f"[{item['id']}]={lua_string(chr(9).join(fields))},")
    lines.append("}")
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines) + "\n")
    return f"{shown(path)} ({path.stat().st_size / 1e6:.1f} MB)"


EXPORTS = [models_json, models_addon]


def write_all(database):
    db = sqlite3.connect(database)
    try:
        return [export(db) for export in EXPORTS]
    finally:
        db.close()
